/**
 * Разбор молдавского номера — ЕДИНЫЕ правила для браузера и для сервера
 * (2026-09-19). До этого маска поля и `normalizePhone` разбирали строку
 * по-разному, и это давало мусор: поле брало просто первые восемь цифр, так
 * что вставка `+37360123456` превращалась в `37360123`, а `060123456` — в
 * `06012345`, и оба потом проходили проверку на сервере как «валидные».
 *
 * Здесь одна функция снятия префиксов, поверх которой живут обе роли:
 *  - поле ввода обрезает результат до восьми цифр (оно физически столько и
 *    вмещает) — `toLocalPhoneDigits`;
 *  - сервер НЕ обрезает — `normalizePhone`: лишние цифры должны провалить
 *    `PHONE_PATTERN`, а не молча превратиться в чужой номер.
 */

/** Местный номер: ровно столько цифр после кода страны. */
export const LOCAL_PHONE_LENGTH = 8

/** Код страны в том виде, в каком он показан рядом с полем ввода. */
export const PHONE_PREFIX = '+373'

/** Международный префикс набора (`00`) вместе с кодом страны. */
const DIAL_PREFIX = '00373'
/** Код страны без префикса набора: так номер приходит из `+373…` и `373…`. */
const COUNTRY_CODE = '373'
/** Национальный префикс: ноль перед местным номером, `060 123 456`. */
const TRUNK_PREFIX = '0'

/**
 * Цифры номера без служебных префиксов, БЕЗ обрезки по длине.
 *
 * Префиксы снимаются только пока цифр больше, чем в местном номере, — иначе
 * настоящий восьмизначный номер, начинающийся с `373` или `0`, был бы
 * искалечен: у местного номера этих префиксов нет по определению, они всегда
 * «лишние» сверх восьми цифр.
 *
 * Цикл, а не три отдельных `if`: записи смешивают префиксы (`0 373 60 123 456`
 * — и ноль, и код страны), и порядок снятия заранее неизвестен. Каждая ветка
 * укорачивает строку хотя бы на символ, нераспознанный остаток выходит через
 * `break`, поэтому цикл конечен.
 *
 * Обрезки короче восьми цифр возвращаются как есть — это нормальное состояние
 * поля, пока человек ещё набирает номер.
 */
export function stripPhonePrefixes(value: string): string {
  let digits = value.replace(/\D/g, '')

  while (digits.length > LOCAL_PHONE_LENGTH) {
    if (digits.startsWith(DIAL_PREFIX)) digits = digits.slice(DIAL_PREFIX.length)
    else if (digits.startsWith(COUNTRY_CODE)) digits = digits.slice(COUNTRY_CODE.length)
    else if (digits.startsWith(TRUNK_PREFIX)) digits = digits.slice(TRUNK_PREFIX.length)
    else break
  }

  return digits
}

/**
 * Значение для поля ввода: цифры местного номера, максимум восемь.
 *
 * Обрезка — именно здесь, а не в `stripPhonePrefixes`: поле вмещает восемь
 * цифр и показывает ровно то, что уйдёт на сервер, поэтому «лишнее» при
 * вставке человек видит отрезанным сразу. На сервере обрезки быть не должно
 * (см. `normalizePhone`).
 */
export const toLocalPhoneDigits = (value: string): string =>
  stripPhonePrefixes(value).slice(0, LOCAL_PHONE_LENGTH)

/** «60 123 456» — читаемая группировка для поля ввода. */
export function formatLocalPhone(digits: string): string {
  const clean = toLocalPhoneDigits(digits)
  const parts = [clean.slice(0, 2), clean.slice(2, 5), clean.slice(5, 8)].filter(Boolean)
  return parts.join(' ')
}

/**
 * Номер в каноничном виде `+373XXXXXXXX` — то, что хранится в базе и с чем
 * сверяются телефоны промокодов.
 *
 * **Длина намеренно не подрезается.** Обрезать здесь значило бы принимать
 * `373601234567890` как `+37360123456`: сервер сам сочинил бы правдоподобный
 * номер из заведомо неверного ввода. Лишние цифры остаются в строке и честно
 * валят `PHONE_PATTERN`.
 *
 * Функция идемпотентна на уже нормализованных значениях (`+373` + 8 цифр →
 * 11 цифр → снимается код страны → те же 8), поэтому сверка сохранённых
 * номеров с введёнными не ломается — в том числе для номеров, записанных до
 * этой правки.
 */
export const normalizePhone = (value: string): string => `${PHONE_PREFIX}${stripPhonePrefixes(value)}`

/**
 * Каноничный номер: `+373` и **ровно восемь** цифр.
 *
 * Первая цифра намеренно не проверяется: диапазоны мобильных и городских
 * номеров Молдовы меняются, и зашитый сюда список операторов начал бы
 * отвергать настоящие номера раньше, чем принёс бы пользу.
 */
export const PHONE_PATTERN = /^\+373\d{8}$/

/** Проверка номера в любом виде: нормализуем и сверяем с каноном. */
export const isValidPhone = (value: string): boolean => PHONE_PATTERN.test(normalizePhone(value))
